/** Check whether the current process token has Administrator elevation. */
static int mb_is_elevated(void) {
    HANDLE tok = NULL;
    if (!OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, &tok)) return 0;
    TOKEN_ELEVATION elev;
    DWORD cb = sizeof(elev);
    int ok = GetTokenInformation(tok, TokenElevation, &elev, sizeof(elev), &cb) && elev.TokenIsElevated;
    CloseHandle(tok);
    return ok;
}

/** Relaunch the current executable with UAC elevation if not already admin. Returns 1 if relaunched. */
static int mb_ensure_admin(int argc, char **argv) {
    if (mb_is_elevated()) return 0;
    char exePath[MAX_PATH] = {0};
    GetModuleFileNameA(NULL, exePath, MAX_PATH);
    char params[2048] = {0};
    for (int i = 1; i < argc; i++) {
        if (strlen(params) + strlen(argv[i]) + 4 < sizeof(params)) {
            if (params[0]) strcat(params, " ");
            strcat(params, "\"");
            strcat(params, argv[i]);
            strcat(params, "\"");
        }
    }
    SHELLEXECUTEINFOA sei;
    ZeroMemory(&sei, sizeof(sei));
    sei.cbSize = sizeof(sei);
    sei.lpVerb = "runas";
    sei.lpFile = exePath;
    sei.lpParameters = params[0] ? params : NULL;
    sei.nShow = SW_SHOWNORMAL;
    if (ShellExecuteExA(&sei)) return 1;
    printf("[ERR] Administrator privileges required.\n");
    return -1;
}

/** Check if hardware ID targets Apple MacBook USB NCM Composite Parent. */
static int mb_is_apple_ncm_parent_hwid(const char *hwid) {
    if (!hwid || !hwid[0]) return 0;
    int isAppleNcm = (strstr(hwid, "VID_05AC&PID_1902") != NULL) || (strstr(hwid, "VID_05AC&PID_1905") != NULL);
    int isChildMi  = (strstr(hwid, "&MI_") != NULL);
    return isAppleNcm && !isChildMi;
}

/** Read INF file in C:\Windows\INF and verify it was generated by libwdi for VID_05AC&PID_1902/1905. */
static int mb_is_safe_libwdi_apple_inf(const char *infName) {
    if (!infName || _strnicmp(infName, "oem", 3) != 0) return 0;
    size_t nameLen = strlen(infName);
    if (nameLen < 8 || nameLen >= 60 || _stricmp(infName + nameLen - 4, ".inf") != 0) return 0;
    if (strstr(infName, "..") != NULL) return 0;
    for (size_t k = 0; k < nameLen; k++) {
        unsigned char c = (unsigned char)infName[k];
        if (!((c >= '0' && c <= '9') || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_' || c == '-' || c == '.'))
            return 0;
    }
    char winDir[MAX_PATH] = {0}, fullPath[512] = {0};
    GetWindowsDirectoryA(winDir, MAX_PATH);
    snprintf(fullPath, sizeof(fullPath), "%s\\INF\\%s", winDir, infName);

    FILE *f = fopen(fullPath, "rb");
    if (!f) return 0;
    char buf[16384];
    size_t n = fread(buf, 1, sizeof(buf) - 1, f);
    fclose(f);
    buf[n] = '\0';

    char ascii[16384];
    size_t ai = 0;
    for (size_t i = 0; i < n && ai + 1 < sizeof(ascii); i++) {
        if (buf[i] != '\0') ascii[ai++] = buf[i];
    }
    ascii[ai] = '\0';

    int hasLibwdi = (strstr(ascii, "libwdi") != NULL);
    int hasApple  = (strstr(ascii, "VID_05AC&PID_1902") != NULL) || (strstr(ascii, "VID_05AC&PID_1905") != NULL);
    return hasLibwdi && hasApple;
}

static void mb_add_unique_inf(char list[16][64], int *count, const char *infName) {
    if (!infName || !infName[0] || *count >= 16) return;
    for (int j = 0; j < *count; j++) {
        if (_stricmp(list[j], infName) == 0) return;
    }
    snprintf(list[*count], 64, "%s", infName);
    (*count)++;
}

/** Run a command via _popen and stream lines converted from OEM codepage to UTF-8. */
static int mb_run_cmd_utf8(const char *cmd) {
    FILE *fp = _popen(cmd, "r");
    if (!fp) return -1;
    char raw[1024];
    while (fgets(raw, sizeof(raw), fp)) {
        size_t len = strlen(raw);
        while (len > 0 && (raw[len - 1] == '\n' || raw[len - 1] == '\r')) raw[--len] = '\0';
        if (len == 0) continue;
        wchar_t wbuf[1024];
        int wlen = MultiByteToWideChar(CP_OEMCP, 0, raw, (int)len, wbuf, 1023);
        if (wlen > 0) {
            wbuf[wlen] = L'\0';
            char u8[2048];
            int ulen = WideCharToMultiByte(CP_UTF8, 0, wbuf, wlen, u8, sizeof(u8) - 1, NULL, NULL);
            if (ulen > 0) {
                u8[ulen] = '\0';
                printf("  %s\n", u8);
            }
        } else {
            printf("  %s\n", raw);
        }
        fflush(stdout);
    }
    return _pclose(fp);
}

/** Fast Win32 process termination by executable basename (avoids slow taskkill/WMI overhead). */
static int mb_kill_process_by_name(const char *exeName) {
    HANDLE snap = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);
    if (snap == INVALID_HANDLE_VALUE) return 0;
    PROCESSENTRY32 pe;
    pe.dwSize = sizeof(pe);
    int killed = 0;
    DWORD selfPid = GetCurrentProcessId();
    if (Process32First(snap, &pe)) {
        do {
            if (pe.th32ProcessID == selfPid) continue;
            if (_stricmp(pe.szExeFile, exeName) == 0) {
                HANDLE hProc = OpenProcess(PROCESS_TERMINATE | SYNCHRONIZE, FALSE, pe.th32ProcessID);
                if (hProc) {
                    if (TerminateProcess(hProc, 1)) {
                        WaitForSingleObject(hProc, 1500);
                        killed++;
                        printf("[RESTORE] 已终止运行中的 %s (PID %lu)\n", exeName, (unsigned long)pe.th32ProcessID);
                        fflush(stdout);
                    }
                    CloseHandle(hProc);
                }
            }
        } while (Process32Next(snap, &pe));
    }
    CloseHandle(snap);
    return killed;
}

/** Uninstall libwdi WinUSB INF bound to Apple 05AC:1902/1905 and restore stock usbccgp driver. */
static int mb_restore_apple_driver(void) {
    printf("[RESTORE] 正在停止后台 USB 隧道进程...\n");
    fflush(stdout);
    int killed = mb_kill_process_by_name("omniflow-usb.exe") + mb_kill_process_by_name("MacBridge.exe");
    if (killed > 0) {
        Sleep(200);
    }

    char targetInfs[16][64] = {{0}};
    int targetCount = 0;

    /* 1. Fast scan present USB devices first */
    HDEVINFO hAll = SetupDiGetClassDevsA(NULL, "USB", NULL, DIGCF_ALLCLASSES | DIGCF_PRESENT);
    if (hAll != INVALID_HANDLE_VALUE) {
        SP_DEVINFO_DATA did;
        did.cbSize = sizeof(did);
        for (DWORD i = 0; SetupDiEnumDeviceInfo(hAll, i, &did); i++) {
            char hwid[1024] = {0}, svc[256] = {0};
            SetupDiGetDeviceRegistryPropertyA(hAll, &did, SPDRP_HARDWAREID, NULL, (PBYTE)hwid, sizeof(hwid) - 1, NULL);
            if (!mb_is_apple_ncm_parent_hwid(hwid)) continue;

            SetupDiGetDeviceRegistryPropertyA(hAll, &did, SPDRP_SERVICE, NULL, (PBYTE)svc, sizeof(svc) - 1, NULL);
            HKEY hkDrv = SetupDiOpenDevRegKey(hAll, &did, DICS_FLAG_GLOBAL, 0, DIREG_DRV, KEY_READ);
            char infPath[128] = {0}, provider[128] = {0};
            if (hkDrv != INVALID_HANDLE_VALUE) {
                DWORD sz1 = sizeof(infPath) - 1, sz2 = sizeof(provider) - 1;
                RegQueryValueExA(hkDrv, "InfPath", NULL, NULL, (LPBYTE)infPath, &sz1);
                RegQueryValueExA(hkDrv, "ProviderName", NULL, NULL, (LPBYTE)provider, &sz2);
                RegCloseKey(hkDrv);
            }
            printf("[FOUND] %s | Service=%s | INF=%s | Provider=%s\n",
                   hwid, svc[0] ? svc : "(none)", infPath[0] ? infPath : "(none)", provider[0] ? provider : "(none)");
            fflush(stdout);

            if (_stricmp(svc, "WinUSB") == 0 && mb_is_safe_libwdi_apple_inf(infPath)) {
                mb_add_unique_inf(targetInfs, &targetCount, infPath);
            }
        }
        SetupDiDestroyDeviceInfoList(hAll);
    }

    /* 2. Fast fallback scan of C:\Windows\INF\oem*.inf (handles unplugged cable without slow SetupDi ghost scan) */
    char winDir[MAX_PATH] = {0}, pattern[512] = {0};
    GetWindowsDirectoryA(winDir, MAX_PATH);
    snprintf(pattern, sizeof(pattern), "%s\\INF\\oem*.inf", winDir);
    WIN32_FIND_DATAA fd;
    HANDLE hFind = FindFirstFileA(pattern, &fd);
    if (hFind != INVALID_HANDLE_VALUE) {
        do {
            if (mb_is_safe_libwdi_apple_inf(fd.cFileName)) {
                mb_add_unique_inf(targetInfs, &targetCount, fd.cFileName);
            }
        } while (FindNextFileA(hFind, &fd));
        FindClose(hFind);
    }

    int removedCount = 0;
    for (int i = 0; i < targetCount; i++) {
        char cmd[320];
        snprintf(cmd, sizeof(cmd), "pnputil /delete-driver %.63s /uninstall /force 2>&1", targetInfs[i]);
        printf("[RESTORE] 卸载驱动包: %s\n", targetInfs[i]);
        fflush(stdout);
        if (mb_run_cmd_utf8(cmd) == 0) removedCount++;
    }

    if (removedCount > 0) {
        printf("[RESTORE] 重新扫描 USB 设备以恢复原厂 usbccgp...\n");
        fflush(stdout);
        mb_run_cmd_utf8("pnputil /scan-devices 2>&1");
        Sleep(1000);
    } else {
        printf("[INFO] 未发现需要卸载的 libwdi WinUSB 驱动，当前已是原厂状态或未安装过。\n");
        fflush(stdout);
    }

    HDEVINFO hNow = SetupDiGetClassDevsA(NULL, "USB", NULL, DIGCF_ALLCLASSES | DIGCF_PRESENT);
    if (hNow != INVALID_HANDLE_VALUE) {
        SP_DEVINFO_DATA did;
        did.cbSize = sizeof(did);
        for (DWORD i = 0; SetupDiEnumDeviceInfo(hNow, i, &did); i++) {
            char hwid[1024] = {0}, svc[256] = {0};
            SetupDiGetDeviceRegistryPropertyA(hNow, &did, SPDRP_HARDWAREID, NULL, (PBYTE)hwid, sizeof(hwid) - 1, NULL);
            if (!mb_is_apple_ncm_parent_hwid(hwid)) continue;
            SetupDiGetDeviceRegistryPropertyA(hNow, &did, SPDRP_SERVICE, NULL, (PBYTE)svc, sizeof(svc) - 1, NULL);
            printf("[AFTER] %s | Service=%s\n", hwid, svc[0] ? svc : "(none)");
            fflush(stdout);
        }
        SetupDiDestroyDeviceInfoList(hNow);
    }

    printf("[OK] 原厂驱动恢复完成。\n");
    fflush(stdout);
    return 0;
}

